import React from "react";
import LocaleProvider from "@douyinfe/semi-ui/lib/es/locale/localeProvider";
import enUS from "@douyinfe/semi-ui/lib/es/locale/source/en_US";
import zhCN from "@douyinfe/semi-ui/lib/es/locale/source/zh_CN";
import { connect } from "react-redux";

function DashboardLocale({ language, children }) {
  const locale = language || localStorage.getItem("locale") || "en-US";
  return (
    <LocaleProvider locale={locale === "zh-CN" ? zhCN : enUS}>
      {children}
    </LocaleProvider>
  );
}

export default connect(({ global }) => ({ language: global.language }))(
  DashboardLocale,
);
